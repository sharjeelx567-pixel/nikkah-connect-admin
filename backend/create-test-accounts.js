// ── Create accounts ──────────────────────────────────────────────────────────
async function createAccount(emailData) {
  const { email, password, profile } = emailData;

  // 1. Create or get Firebase Auth user
  let uid;
  try {
    const existing = await auth.getUserByEmail(email);
    uid = existing.uid;
    console.log(`[EXISTS] ${email} → uid: ${uid}`);
  } catch {
    const newUser = await auth.createUser({ email, password, displayName: profile.displayName });
    uid = newUser.uid;
    console.log(`[CREATED] ${email} → uid: ${uid}`);
  }

  // 2. Build full Firestore document
  const doc = {
    uid,
    email,
    phoneNumber: null,
    ...profile,
    profileCompleted: true,
    compatibilityCompleted: true,
    photosApproved: true,
    isVerified: true,
    verificationStatus: 'approved',
    isPremium: false,
    otpVerified: true,
    completionPercentage: 100,
    onboardingStep: 10,
    isDormant: false,
    isPaused: false,
    pauseReason: null,
    role: profile.role || 'candidate',
    profileCreator: profile.profileCreator || 'Self',
    createdAt: now,
    updatedAt: now,
    lastLoginAt: now,
    galleryImages: [],
    voiceIntroUrl: null,
    profileImage: null,
    pendingProfileImage: null,
    pendingGalleryImages: [],
    photoStatus: null,
    familyId: null,
    divorceDetails: null,
    marriageIntention: 'Serious',
    niyyatTimeline: profile.niyyatTimeline || 2,
    propertyDetail: null,
    isPolygamySeeker: false,
    openToPolygamy: false,
    currentMarriageDeclaration: null,
    openToRemarriage: false,
    remarriageMatchingPool: false,
    raisedIn: profile.raisedIn || profile.permanentCity,
    nationality: profile.nationality || 'Pakistani',
  };

  // Remove undefined fields
  Object.keys(doc).forEach(k => { if (doc[k] === undefined) delete doc[k]; });

  await db.collection('users').doc(uid).set(doc, { merge: true });
  console.log(`[SAVED]   Firestore profile saved for ${profile.displayName}`);
  return uid;
}

async function main() {
  console.log('\n=== Creating 3 Male Accounts ===');
  for (const m of males) await createAccount(m);

  console.log('\n=== Creating 3 Female Accounts ===');
  for (const f of females) await createAccount(f);

  console.log('\n✅ All 6 accounts created successfully!');
  console.log('\nCredentials summary:');
  [...males, ...females].forEach(u => {
    console.log(`  ${u.profile.gender} | ${u.profile.displayName} | ${u.email} | ${u.password}`);
  });
  process.exit(0);
}

main().catch(e => { console.error('ERROR:', e); process.exit(1); });
